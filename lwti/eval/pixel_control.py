"""Pixel-space control for the invariance-vs-error correlation (E0a).

Feature invariance (invariance.py) correlates with the CER rise across damage
settings. But a damage that barely changes the PIXELS would also barely
change the features and barely hurt, whatever the model learnt. So:

1. Pixel invariance per damage family x level, on the same 500 test lines
   and the same damaged images as invariance.py (sample random_state=0,
   damage rng seeded (1234, line)):
       pix_cos  = mean cosine similarity(clean input, damaged input),
                  input = 1 - gray/255 (ink = 1, as the network sees it)
       pix_corr = the same after subtracting each line's mean
                  (Pearson; insensitive to a uniform paper-tone shift)
   For runs trained with --bgnorm the pixels are taken after
   background normalisation (that is their input).
2. Per run, Spearman rho against the CER ratio (results/robustness.csv),
   next to the feature-invariance rho (results/invariance.csv), and the
   partial Spearman of feature invariance vs CER ratio after rank-regressing
   out pixel invariance (pix_cos).

Model-independent, no GPU. Usage:
    python -m lwti.eval.pixel_control [--data iam] [--n 500]
Output: results/pixel_invariance.csv, results/tables/pixel_control.md
"""
import argparse
import json
import os

import numpy as np
import pandas as pd
from scipy.stats import pearsonr, rankdata, spearmanr, t as t_dist

from lwti.damage import families as F
from lwti.data.common import bg_normalise
from lwti.data.dataset import LineDataset, load_frame
from lwti.train.train_ctc import RESULTS, ROOT


def ink(g):
    return 1.0 - g.astype(np.float64).ravel() / 255.0


def cos(a, b):
    return float(a @ b / (np.linalg.norm(a) * np.linalg.norm(b) + 1e-12))


def pixel_invariance(df):
    clean = LineDataset(df, None, transform=None, seed=1234)
    rows = []
    for fam in F.FAMILIES:
        for lv in range(3):
            dmg = LineDataset(df, None, transform=F.fixed(fam, lv), seed=1234)
            r = {"family": fam, "level": lv}
            vals = {k: [] for k in ["pix_cos", "pix_corr", "pix_cos_bgnorm", "pix_corr_bgnorm"]}
            for i in range(len(df)):
                g0 = ((1 - clean[i][0][0].numpy()) * 255).round().astype(np.uint8)
                g1 = ((1 - dmg[i][0][0].numpy()) * 255).round().astype(np.uint8)
                for sfx, a, b in [("", g0, g1), ("_bgnorm", bg_normalise(g0), bg_normalise(g1))]:
                    a, b = ink(a), ink(b)
                    vals["pix_cos" + sfx].append(cos(a, b))
                    vals["pix_corr" + sfx].append(cos(a - a.mean(), b - b.mean()))
            r.update({k: float(np.mean(v)) for k, v in vals.items()})
            rows.append(r)
            print(f"  {fam:12s} level {lv}  pix_cos {r['pix_cos']:.3f}  pix_corr {r['pix_corr']:.3f}", flush=True)
    return pd.DataFrame(rows)


def partial_spearman(x, y, z):
    """Spearman of x and y after linearly regressing rank(z) out of rank(x) and rank(y)."""
    rx, ry, rz = rankdata(x), rankdata(y), rankdata(z)
    Z = np.c_[np.ones_like(rz), rz]
    ex = rx - Z @ np.linalg.lstsq(Z, rx, rcond=None)[0]
    ey = ry - Z @ np.linalg.lstsq(Z, ry, rcond=None)[0]
    r = pearsonr(ex, ey)[0]
    n = len(x)
    tt = r * np.sqrt((n - 3) / max(1 - r * r, 1e-12))
    return r, 2 * t_dist.sf(abs(tt), n - 3)


def uses_bgnorm(run):
    p = os.path.join(ROOT, "runs", run, "config.json")
    return os.path.exists(p) and json.load(open(p)).get("bgnorm", False)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", default="iam")
    ap.add_argument("--n", type=int, default=500)
    args = ap.parse_args()

    df = load_frame(args.data, "test").sample(args.n, random_state=0).reset_index(drop=True)  # as invariance.py
    pix = pixel_invariance(df)
    pix.to_csv(os.path.join(RESULTS, "pixel_invariance.csv"), index=False)

    inv = pd.read_csv(os.path.join(RESULTS, "invariance.csv"))
    rob = pd.read_csv(os.path.join(RESULTS, "robustness.csv"))
    rob = rob[(rob.family != "clean") & (rob.data == args.data)].drop_duplicates(["run", "family", "level"], keep="last")
    rob["level"] = rob.level.astype(int)
    d = rob[["run", "family", "level", "ratio"]].merge(inv[["run", "family", "level", "invariance"]],
                                                       on=["run", "family", "level"]).merge(pix, on=["family", "level"])

    out = ["# Pixel-space control (auto-generated by lwti/eval/pixel_control.py)", "",
           f"{args.n} {args.data} test lines, the same lines and damaged images as invariance.py. "
           "pix_cos = mean cosine similarity between clean and damaged input pixels (ink = 1); "
           "pix_corr = the same with each line's mean removed.", "",
           "## Pixel invariance per damage setting", "",
           "| Damage | Level | pix_cos | pix_corr | pix_cos (bgnorm) | mean feature invariance | mean CER ratio |",
           "|---|---|---|---|---|---|---|"]
    per = d.groupby(["family", "level"])[["invariance", "ratio"]].mean()
    for _, r in pix.iterrows():
        fi, ra = per.loc[(r.family, r.level)] if (r.family, r.level) in per.index else (np.nan, np.nan)
        out.append(f"| {r.family} | {r.level} | {r.pix_cos:.3f} | {r.pix_corr:.3f} | {r.pix_cos_bgnorm:.3f} | "
                   f"{fi:.3f} | {ra:.2f} |")

    out += ["", "## Spearman rho with the CER ratio, per run (n = 21 damage settings)", "",
            "Feature = feature invariance (invariance.csv). Pixel = pix_cos / pix_corr. "
            "Partial = feature invariance vs CER ratio after rank-regressing out pix_cos (p from t, n - 3 df).", "",
            "| Run | Feature ρ | Pixel ρ (cos) | Pixel ρ (corr) | ρ(feature, pixel) | Partial ρ feature \\| pixel | p (partial) |",
            "|---|---|---|---|---|---|---|"]
    rows = []
    for run, g in d.groupby("run"):
        sfx = "_bgnorm" if uses_bgnorm(run) else ""
        pc, pr = g["pix_cos" + sfx], g["pix_corr" + sfx]
        r = dict(feat=spearmanr(g.invariance, g.ratio)[0], pix=spearmanr(pc, g.ratio)[0],
                 pixc=spearmanr(pr, g.ratio)[0], fp=spearmanr(g.invariance, pc)[0])
        r["part"], r["p"] = partial_spearman(g.invariance, g.ratio, pc)
        rows.append(r)
        out.append(f"| {run}{' (bgnorm)' if sfx else ''} | {r['feat']:.2f} | {r['pix']:.2f} | {r['pixc']:.2f} | "
                   f"{r['fp']:.2f} | {r['part']:.2f} | {r['p']:.3f} |")
    m = pd.DataFrame(rows).mean()
    out += [f"| **mean of {len(rows)} runs** | **{m.feat:.2f}** | **{m.pix:.2f}** | **{m.pixc:.2f}** | **{m.fp:.2f}** | "
            f"**{m.part:.2f}** | |", "",
            "Pixel invariance is the same for every model (except bgnorm runs), so it cannot explain the "
            "across-model comparison in controls.md section 2; it only controls the across-damage correlation.", ""]
    path = os.path.join(RESULTS, "tables", "pixel_control.md")
    with open(path, "w") as fh:
        fh.write("\n".join(out) + "\n")
    print("\n".join(out))
    print("wrote", path)


if __name__ == "__main__":
    main()
