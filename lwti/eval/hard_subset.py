"""CER on the most-damaged CATMuS test lines, per run tag (mean over seeds).

For each damage statistic (paper level, midtone / show-through, contrast) the
"hard subset" is the most-damaged quartile of the CATMuS test lines, chosen
exactly as in real_damage.py: quartiles within each project, oriented by
real_damage.DAMAGE (LOW paper level, HIGH midtone, LOW contrast = more
damaged), pre-binarised lines excluded. The subset depends only on the
measured statistics, so every run is scored on the same lines.

Usage: python -m lwti.eval.hard_subset runs/catmus_crnn_f0.05_s0 runs/...
Output: results/tables/hard_subset.md (+ .csv, one row per run)
"""
import argparse
import json
import os

import pandas as pd

from lwti.eval.real_damage import DAMAGE, per_line
from lwti.train.train_ctc import RESULTS

STATS = {"paper": "paper level (low)", "midtone": "midtone / show-through (high)", "contrast": "contrast (low)"}


def hard_ids(st):
    """statistic -> set of line ids in the most-damaged within-project quartile."""
    out = {}
    for s in STATS:
        q = st.groupby("project")[s].transform(
            lambda v: pd.qcut((DAMAGE[s] * v).rank(method="first"), 4, labels=False) if len(v) >= 8 else pd.NA)
        out[s] = set(st.id[q == 3])
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("runs", nargs="+")
    args = ap.parse_args()
    st = pd.read_csv(os.path.join(RESULTS, "stats", "catmus_test.csv"))
    st = st[~((st.contrast > 0.98) & (st.paper > 0.98))]  # pre-binarised lines, as in real_damage.py
    hard = hard_ids(st)
    rows = []
    for run in args.runs:
        cfg = json.load(open(os.path.join(run, "config.json")))
        d = per_line(run)
        d = d[d.id.isin(set(st.id))]
        r = dict(run=os.path.basename(run.rstrip("/")), tag=cfg.get("tag") or "scratch", frac=cfg["frac"],
                 seed=cfg["seed"], all=d.edits.sum() / d.chars.sum(), n_all=len(d))
        for s, ids in hard.items():
            g = d[d.id.isin(ids)]
            r[s], r["n_" + s] = g.edits.sum() / max(g.chars.sum(), 1), len(g)
        rows.append(r)
    t = pd.DataFrame(rows)
    t.to_csv(os.path.join(RESULTS, "tables", "hard_subset.csv"), index=False)

    n = t.iloc[0]
    lines = ["# CER on the most-damaged quartile of CATMuS test lines (auto-generated by lwti/eval/hard_subset.py)", "",
             f"Quartiles within each project; pre-binarised lines excluded. Lines: all {n.n_all}, "
             + ", ".join(f"{s} {n['n_' + s]}" for s in STATS) + ". Mean over seeds (min-max in brackets).", "",
             "| Tag | Seeds | All lines | " + " | ".join(f"Q4 {v}" for v in STATS.values()) + " |",
             "|---|---|---|" + "---|" * len(STATS)]
    for (tag, fr), g in t.groupby(["tag", "frac"], sort=False):
        cells = [f"{g[c].mean() * 100:.1f}% ({g[c].min() * 100:.1f}-{g[c].max() * 100:.1f})" for c in ["all", *STATS]]
        lines.append(f"| {tag} (f{fr:g}) | {','.join(str(s) for s in sorted(g.seed))} | " + " | ".join(cells) + " |")
    path = os.path.join(RESULTS, "tables", "hard_subset.md")
    with open(path, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print("\n".join(lines))
    print("wrote", path)


if __name__ == "__main__":
    main()
