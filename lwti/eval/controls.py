"""Extra checks on the pilot results (added 10 Nov 2026, after the overnight chain).

1. Does the invariance-vs-error correlation survive when damage strength is held fixed?
   (Spearman rho across the 7 damage types, inside each strength level.)
2. Across models, at one fixed damage setting: is the more invariant model hurt less?
   (Spearman rho across the 8 IAM-10% models, for each of the 21 damage settings.)
3. Does the pretraining recipe change which damage the fine-tuned model resists?
   (Absolute test CER under medium and high damage, by recipe and seed.)

    python -m lwti.eval.controls        -> results/tables/controls.md
"""
import os

import pandas as pd
from scipy.stats import spearmanr

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
NAMES = {"scratch": "no pretraining", "none": "masking only", "handpicked": "+ hand-picked", "derived_v0": "+ derived"}
ORDER = ["scratch", "none", "handpicked", "derived_v0"]


def main():
    inv = pd.read_csv(os.path.join(ROOT, "results/invariance.csv"))
    rob = pd.read_csv(os.path.join(ROOT, "results/robustness.csv"))
    rob["variant"] = rob.run.str.extract(r"cmae_(\w+?)_f")[0].fillna("scratch")
    d = inv.merge(rob[rob.family != "clean"][["run", "family", "level", "ratio", "cer", "variant"]],
                  on=["run", "family", "level"])
    out = ["# Extra checks on the pilot (auto-generated by lwti/eval/controls.py)", ""]

    out += ["## 1. Invariance vs CER rise with damage strength held fixed", "",
            "Spearman rho across the 7 damage types, inside each strength level (n = 7 per cell).", "",
            "| Run | Low | Medium | High |", "|---|---|---|---|"]
    rows = []
    for run, g in d.groupby("run"):
        r = [spearmanr(h.invariance, h.ratio)[0] for _, h in g.groupby("level")]
        rows.append(r)
        out.append(f"| {run} | " + " | ".join(f"{x:.2f}" for x in r) + " |")
    m = pd.DataFrame(rows).mean()
    out += ["| **mean of 9 runs** | " + " | ".join(f"**{x:.2f}**" for x in m) + " |", ""]

    ten = d[d.run.str.contains("f0.1")]
    out += ["## 2. Across models at one fixed damage setting", "",
            "Spearman rho across the 8 IAM-10% models (4 recipes x 2 seeds) between a model's invariance to a "
            "damage setting and its CER rise under it.", "",
            "| Damage | Low | Medium | High |", "|---|---|---|---|"]
    rhos = []
    for fam, g in ten.groupby("family"):
        r = [spearmanr(h.invariance, h.ratio)[0] for _, h in g.groupby("level")]
        rhos += r
        out.append(f"| {fam} | " + " | ".join(f"{x:.2f}" for x in r) + " |")
    neg = sum(x < 0 for x in rhos)
    out += ["", f"Negative in {neg} of {len(rhos)} settings; mean rho {sum(rhos) / len(rhos):.2f}.", ""]

    out += ["## 3. Test CER under synthetic damage, by pretraining recipe (IAM, 10% labels)", "",
            "Seed 0 / seed 1, per cent. Ink loss was held out of every pretraining recipe.", ""]
    r10 = rob[rob.run.str.contains("f0.1")]
    clean = r10.groupby(["variant", "seed"]).cer_clean.first().unstack() * 100
    for lvl, name in [(1, "Medium"), (2, "High")]:
        t = r10[r10.level == lvl].pivot_table(index="family", columns=["variant", "seed"], values="cer") * 100
        out += [f"### {name} strength", "", "| Damage | " + " | ".join(NAMES[v] for v in ORDER) + " |",
                "|---|" + "---|" * len(ORDER)]
        if lvl == 1:
            out.append("| (clean test) | " + " | ".join(f"{clean.loc[v, 0]:.1f} / {clean.loc[v, 1]:.1f}" for v in ORDER) + " |")
        for fam in t.index:
            out.append(f"| {fam} | " + " | ".join(f"{t.loc[fam, (v, 0)]:.1f} / {t.loc[fam, (v, 1)]:.1f}" for v in ORDER) + " |")
        out.append("")
    path = os.path.join(ROOT, "results/tables/controls.md")
    with open(path, "w") as fh:
        fh.write("\n".join(out) + "\n")
    print("\n".join(out))
    print("wrote", path)


if __name__ == "__main__":
    main()
