"""Extra checks on the pilot results (added 10 Nov 2026, after the overnight chain;
recipe grouping made explicit and E1/E0b arms added 16 Nov 2026).

1. Does the invariance-vs-error correlation survive when damage strength is held fixed?
   (Spearman rho across the 7 damage types, inside each strength level.)
2. Across models, at one fixed damage setting: is the more invariant model hurt less?
   (Spearman rho across the IAM-10% models, for each of the 21 damage settings.)
3. Does the training recipe change which damage the fine-tuned model resists?
   (Absolute test CER under medium and high damage, by recipe and seed.)

Recipes (from the run name <data>_crnn[_<tag>]_f<frac>_s<seed>):
  scratch (no tag), cmae_<none|handpicked|derived_v0> (CNN pretraining),
  aug_handpicked / aug_derived_v0 (damage recipe as training augmentation, E1),
  bgnorm (background normalisation, E0b).

    python -m lwti.eval.controls [--out PATH]   -> results/tables/controls.md
"""
import argparse
import os
import re

import pandas as pd
from scipy.stats import spearmanr

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
NAMES = {"scratch": "no pretraining", "none": "masking only", "handpicked": "+ hand-picked", "derived_v0": "+ derived",
         "aug_handpicked": "aug: hand-picked", "aug_derived_v0": "aug: derived", "bgnorm": "bg normalisation"}
PRETRAIN = ["scratch", "none", "handpicked", "derived_v0"]   # the original pretraining comparison
EXTRA = ["aug_handpicked", "aug_derived_v0", "bgnorm"]        # E1 / E0b arms
ORDER = PRETRAIN + EXTRA
RUN_RE = re.compile(r"^[a-z]+_crnn(?:_(.+?))?_f[\d.]+_s\d+$")


def recipe(run):
    """Run name -> recipe key in ORDER (or the raw tag if unknown, None if not a CRNN run)."""
    m = RUN_RE.match(run)
    if not m:
        return None
    tag = m.group(1) or ""
    if tag == "":
        return "scratch"
    if tag.startswith("cmae_"):
        return tag[len("cmae_"):]
    return tag


def cell(t, key, v, seeds):
    vals = [t.get((key, v, s)) for s in seeds]
    return " / ".join("–" if x is None or pd.isna(x) else f"{x:.1f}" for x in vals)


def main(out_path=None):
    inv = pd.read_csv(os.path.join(ROOT, "results/invariance.csv"))
    rob = pd.read_csv(os.path.join(ROOT, "results/robustness.csv"))
    rob["variant"] = rob.run.map(recipe)
    rob = rob[rob.variant.notna()]
    d = inv.merge(rob[rob.family != "clean"][["run", "family", "level", "ratio", "cer", "variant"]],
                  on=["run", "family", "level"])
    out = ["# Extra checks on the pilot (auto-generated by lwti/eval/controls.py)", ""]

    out += ["## 1. Invariance vs CER rise with damage strength held fixed", "",
            "Spearman rho across the 7 damage types, inside each strength level (n = 7 per cell).", "",
            "| Run | Low | Medium | High |", "|---|---|---|---|"]
    rows = []
    for run, g in d.groupby("run"):
        r = [spearmanr(h.invariance, h.ratio)[0] for _, h in g.groupby("level")]
        rows.append(r)
        out.append(f"| {run} | " + " | ".join(f"{x:.2f}" for x in r) + " |")
    m = pd.DataFrame(rows).mean()
    out += [f"| **mean of {len(rows)} runs** | " + " | ".join(f"**{x:.2f}**" for x in m) + " |", ""]

    ten = d[d.run.str.contains("f0.1")]
    pre = ten[ten.variant.isin(PRETRAIN)]
    n_rec, n_mod = pre.variant.nunique(), pre.run.nunique()
    out += ["## 2. Across models at one fixed damage setting", "",
            f"Spearman rho across the {n_mod} IAM-10% pretraining-comparison models ({n_rec} recipes, "
            f"{', '.join(f'{v} x{pre[pre.variant == v].run.nunique()}' for v in PRETRAIN if (pre.variant == v).any())}) "
            "between a model's invariance to a damage setting and its CER rise under it.", "",
            "| Damage | Low | Medium | High |", "|---|---|---|---|"]
    rhos = []
    for fam, g in pre.groupby("family"):
        r = [spearmanr(h.invariance, h.ratio)[0] for _, h in g.groupby("level")]
        rhos += r
        out.append(f"| {fam} | " + " | ".join(f"{x:.2f}" for x in r) + " |")
    neg = sum(x < 0 for x in rhos)
    out += ["", f"Negative in {neg} of {len(rhos)} settings; mean rho {sum(rhos) / len(rhos):.2f}."]
    if ten.variant.isin(EXTRA).any():
        allr = [spearmanr(h.invariance, h.ratio)[0] for _, h in ten.groupby(["family", "level"])]
        out.append(f"Including the augmentation / bgnorm models ({ten.run.nunique()} models): negative in "
                   f"{sum(x < 0 for x in allr)} of {len(allr)} settings; mean rho {sum(allr) / len(allr):.2f}.")
    else:
        out.append("Augmentation / bgnorm models: no runs yet.")
    out.append("")

    r10 = rob[rob.run.str.contains("f0.1")]
    present = [v for v in ORDER if (r10.variant == v).any()]
    missing = [v for v in ORDER if v not in present]
    seeds = sorted(int(s) for s in r10.seed.unique())
    out += ["## 3. Test CER under synthetic damage, by training recipe (IAM, 10% labels)", "",
            f"Seed {' / seed '.join(map(str, seeds))}, per cent ('–' = seed not run). Ink loss was held out of "
            "every pretraining and augmentation recipe.", ""]
    if missing:
        out += [f"{', '.join(NAMES[v] for v in missing)}: no runs yet.", ""]
    clean = (r10.groupby(["variant", "seed"]).cer_clean.first() * 100).to_dict()
    clean = {("clean", v, s): x for (v, s), x in clean.items()}
    for lvl, name in [(1, "Medium"), (2, "High")]:
        t = r10[r10.level == lvl].groupby(["family", "variant", "seed"], sort=False).cer.mean() * 100
        t = t.to_dict()
        out += [f"### {name} strength", "", "| Damage | " + " | ".join(NAMES[v] for v in present) + " |",
                "|---|" + "---|" * len(present)]
        if lvl == 1:
            out.append("| (clean test) | " + " | ".join(cell(clean, "clean", v, seeds) for v in present) + " |")
        for fam in sorted(r10[r10.level == lvl].family.unique()):
            out.append(f"| {fam} | " + " | ".join(cell(t, fam, v, seeds) for v in present) + " |")
        out.append("")
    path = out_path or os.path.join(ROOT, "results/tables/controls.md")
    with open(path, "w") as fh:
        fh.write("\n".join(out) + "\n")
    print("\n".join(out))
    print("wrote", path)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=None, help="write here instead of results/tables/controls.md")
    main(ap.parse_args().out)
